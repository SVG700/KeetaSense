"""Generate the SYNTHETIC sample tape images used by the mock camera.

The 12 images tell a story when the edge demo cycles through them
(rolling window = 3 sections):
  days 1-3   few whiteflies                         -> WAIT
  days 4-6   whiteflies explode, few predators      -> SPRAY
  days 7-9   predators build up and keep pace       -> RELEASE BIOCONTROL
  days 10-12 whiteflies fall again                  -> WAIT

These are drawn by ml/synthetic.py - they are NOT photos of real insects.

Usage:  python -m demo.generate_sample_tape
"""
from __future__ import annotations

from pathlib import Path

import cv2

from ml.synthetic import render_tape

OUT = Path(__file__).resolve().parent / "sample_tape"

# (whitefly, macrolophus, nesidiocoris) for each simulated day
STORY = [
    (6, 1, 0), (9, 0, 1), (12, 1, 0),
    (38, 1, 1), (52, 1, 1), (64, 2, 1),
    (55, 5, 4), (48, 6, 5), (40, 6, 6),
    (18, 4, 3), (10, 3, 2), (7, 2, 2),
]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("tape_*.jpg"):
        old.unlink()
    for day, (wf, mr, nc) in enumerate(STORY, start=1):
        img, _ = render_tape({"whitefly": wf, "macrolophus": mr, "nesidiocoris": nc},
                             1280, 800, seed=1000 + day)
        cv2.imwrite(str(OUT / f"tape_{day:02d}.jpg"), img, [cv2.IMWRITE_JPEG_QUALITY, 85])
    (OUT / "README.txt").write_text(
        "SYNTHETIC sample tape images (generated by demo/generate_sample_tape.py).\n"
        "Not real insects. Used by the edge service in mock mode.\n", encoding="utf-8")
    print(f"[demo] wrote {len(STORY)} SYNTHETIC tape images to {OUT}")


if __name__ == "__main__":
    main()
